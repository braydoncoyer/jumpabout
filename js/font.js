  var CW = 6, CH = 8;

  // draw text; opts: scale, align ('left'|'center'|'right'), shadow colour
  function text(ctx, str, x, y, color, opts) {
    opts = opts || {};
    var s = opts.scale || 1;
    str = String(str);
    var w = width(str, s);
    if (opts.align === 'center') x = Math.round(x - w / 2);
    else if (opts.align === 'right') x = Math.round(x - w);
    if (opts.shadow) draw(ctx, str, x + s, y + s, opts.shadow, s);
    draw(ctx, str, x, y, color, s);
    return w;
  }

  function draw(ctx, str, x, y, color, s) {
    ctx.fillStyle = color;
    for (var i = 0; i < str.length; i++) {
      var ch = str[i];
      var rows = G[ch] || G[ch.toUpperCase()] || G['?'];
      for (var r = 0; r < 7; r++) {
        var bits = rows[r];
        if (!bits) continue;
        for (var c = 0; c < 5; c++) {
          if (bits & (0x10 >> c)) ctx.fillRect(x + (i * CW + c) * s, y + r * s, s, s);
        }
      }
    }
  }

  function width(str, s) { return String(str).length * CW * (s || 1) - (s || 1); }

  window.JA = window.JA || {};
  window.JA.font = { text: text, width: width, CW: CW, CH: CH };
